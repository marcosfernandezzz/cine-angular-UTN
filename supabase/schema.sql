-- Public catalog read policies
create policy "movies public read" on public.movies
for select using (active = true);

create policy "rooms public read" on public.rooms
for select using (active = true);

create policy "seats public read" on public.seats
for select using (true);

create policy "functions public read" on public.cinema_functions
for select using (active = true);

create policy "function seats public read" on public.function_seats
for select using (true);

create policy "products public read" on public.products
for select using (active = true);

create policy "reviews public read" on public.reviews
for select using (true);

-- User profile access
create policy "profile own read" on public.profiles
for select to authenticated
using (id = auth.uid());

create policy "profile own update" on public.profiles
for update to authenticated
using (id = auth.uid())
with check (id = auth.uid());

create policy "purchase own read" on public.purchases
for select to authenticated
using (user_id = auth.uid());

create policy "purchase ticket own read" on public.purchase_tickets
for select to authenticated
using (
  exists (
    select 1 from public.purchases p
    where p.id = purchase_id and p.user_id = auth.uid()
  )
);

create policy "purchase product own read" on public.purchase_products
for select to authenticated
using (
  exists (
    select 1 from public.purchases p
    where p.id = purchase_id and p.user_id = auth.uid()
  )
);

create policy "review own write" on public.reviews
for insert to authenticated
with check (user_id = auth.uid());

create policy "review own update" on public.reviews
for update to authenticated
using (user_id = auth.uid())
with check (user_id = auth.uid());

-- Profile creation after signup
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, email)
  values (new.id, coalesce(new.email, ''));
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

