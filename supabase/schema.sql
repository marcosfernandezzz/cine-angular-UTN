create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  role text not null default 'customer'
    check (role in ('customer', 'admin', 'staff')),
  credit numeric(12,2) not null default 0,
  loyalty_points integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.movies (
  id bigint generated by default as identity primary key,
  name text not null,
  image_url text not null,
  synopsis text not null,
  duration_minutes integer not null check (duration_minutes > 0),
  genres text[] not null default '{}',
  age_rating text not null,
  formats text[] not null default '{}',
  language_modes text[] not null default '{}',
  release_date date not null,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.rooms (
  id bigint generated by default as identity primary key,
  name text not null,
  rows_count integer not null check (rows_count > 0),
  seats_per_row integer not null check (seats_per_row > 0),
  active boolean not null default true
);

create table if not exists public.seats (
  id bigint generated by default as identity primary key,
  room_id bigint not null references public.rooms(id) on delete cascade,
  row_code text not null,
  seat_number integer not null,
  accessible boolean not null default false,
  vip boolean not null default false,
  unique(room_id, row_code, seat_number)
);

create table if not exists public.cinema_functions (
  id bigint generated by default as identity primary key,
  movie_id bigint not null references public.movies(id),
  room_id bigint not null references public.rooms(id),
  starts_at timestamptz not null,
  format text not null check (format in ('2D', '3D', '4D', '5D')),
  language_mode text not null check (language_mode in ('castellano', 'subtitulada')),
  base_price numeric(12,2) not null,
  presale_price numeric(12,2),
  active boolean not null default true
);

create table if not exists public.function_seats (
  id bigint generated by default as identity primary key,
  function_id bigint not null references public.cinema_functions(id) on delete cascade,
  seat_id bigint not null references public.seats(id) on delete cascade,
  status text not null default 'available' check (status in ('available', 'sold')),
  unique(function_id, seat_id)
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null,
  price numeric(12,2) not null,
  stock integer not null default 0,
  active boolean not null default true
);

create table if not exists public.coupons (
  id bigint generated by default as identity primary key,
  code text not null unique,
  discount_percent numeric(5,2),
  discount_amount numeric(12,2),
  valid_from timestamptz not null,
  valid_until timestamptz not null,
  active boolean not null default true
);

create table if not exists public.purchases (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id),
  total numeric(12,2) not null,
  status text not null default 'paid'
    check (status in ('pending', 'paid', 'cancelled', 'used')),
  qr_code uuid not null default gen_random_uuid(),
  created_at timestamptz not null default now(),
  cancelled_at timestamptz
);

create table if not exists public.purchase_tickets (
  id bigint generated by default as identity primary key,
  purchase_id bigint not null references public.purchases(id) on delete cascade,
  function_id bigint not null references public.cinema_functions(id),
  function_seat_id bigint not null references public.function_seats(id),
  price numeric(12,2) not null,
  used_at timestamptz
);

create table if not exists public.purchase_products (
  id bigint generated by default as identity primary key,
  purchase_id bigint not null references public.purchases(id) on delete cascade,
  product_id bigint not null references public.products(id),
  quantity integer not null check (quantity > 0),
  unit_price numeric(12,2) not null,
  collected_at timestamptz
);

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  movie_id bigint not null references public.movies(id) on delete cascade,
  stars integer not null check (stars between 1 and 5),
  comment text,
  created_at timestamptz not null default now(),
  unique(user_id, movie_id)
);

create table if not exists public.loyalty_movements (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  points integer not null,
  reason text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.rewards (
  id bigint generated by default as identity primary key,
  name text not null,
  points_cost integer not null check (points_cost > 0),
  active boolean not null default true
);

create table if not exists public.credit_movements (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  amount numeric(12,2) not null,
  reason text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id),
  action text not null,
  entity_type text not null,
  entity_id text,
  details jsonb,
  created_at timestamptz not null default now()
);

